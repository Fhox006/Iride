package com.metrolist.music.ui.component

import androidx.compose.foundation.layout.Box
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.foundation.background
import androidx.compose.material3.MaterialTheme
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Shape
import androidx.compose.ui.layout.ContentScale
import androidx.compose.ui.platform.LocalContext
import coil3.compose.AsyncImage
import coil3.imageLoader
import coil3.request.ImageRequest
import coil3.request.crossfade
import com.metrolist.music.R
import com.metrolist.music.repository.ChartPlaylistIdentity
import com.metrolist.music.ui.theme.CollectionArtworkShape
import com.metrolist.music.utils.playlistCoverId

@Composable
internal fun PlaylistArtwork(
    title: String,
    thumbnailUrl: String? = null,
    modifier: Modifier = Modifier,
    playlistId: String? = null,
    shape: Shape = CollectionArtworkShape,
    showBadge: Boolean = true,
    expansionTarget: Boolean = false,
) {
    val chart = playlistId?.let(ChartPlaylistIdentity::market)
    // Saved charts may still point at a poster generated by older versions of Iride.
    val artworkUrl = rememberPlaylistCustomCover(playlistId)
        ?: thumbnailUrl?.takeIf { it.isNotBlank() && chart == null }
    val identity = playlistId?.takeIf { it.isNotBlank() }?.let(::playlistCoverId) ?: title
    val patternIndex = (identity.hashCode() and Int.MAX_VALUE) % playlistCoverPatterns.size
    val hasPlaylist = title.isNotBlank()
    val context = LocalContext.current
    val artworkModel = if (hasPlaylist) artworkUrl ?: playlistCoverPatterns[patternIndex] else null
    var artworkReady by remember(artworkModel) { mutableStateOf(artworkModel == null) }
    val target = if (expansionTarget) Modifier.playlistExpansionTarget(ready = artworkReady) else Modifier
    val artworkRequest = remember(context, artworkModel) {
        artworkModel?.let { ImageRequest.Builder(context).data(it).crossfade(false).build() }
    }
    Box(modifier.then(target).clip(shape).background(MaterialTheme.colorScheme.surfaceVariant)) {
        if (artworkRequest != null) {
            AsyncImage(
                model = artworkRequest,
                imageLoader = context.imageLoader,
                contentDescription = null,
                contentScale = ContentScale.Crop,
                placeholder = null,
                error = null,
                onSuccess = { artworkReady = true },
                onError = { artworkReady = true },
                modifier = Modifier.fillMaxSize(),
            )
        }
        if (showBadge && !expansionTarget) PlaylistArtworkBadge(Modifier.fillMaxSize())
    }
}

private val playlistCoverPatterns = listOf(
    R.drawable.playlist_cover_pattern_1,
    R.drawable.playlist_cover_pattern_2,
    R.drawable.playlist_cover_pattern_3,
    R.drawable.playlist_cover_pattern_4,
    R.drawable.playlist_cover_pattern_5,
)
